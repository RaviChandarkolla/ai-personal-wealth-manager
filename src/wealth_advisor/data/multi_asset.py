def facts_for_multi_asset(rec: MultiAssetRecord, as_of: date) -> list[Fact]:
    """Convert a MultiAssetRecord into cited Fact objects."""
    facts: list[Fact] = []
    for k, v in rec.metrics.items():
        facts.append(
            Fact(
                id=f"{rec.code}:{k}",
                name=k,
                value=v,
                citation=Citation(
                    source=rec.source,
                    as_of=as_of,
                    url_or_doc_id=f"{rec.source_url}#{rec.code}",
                ),
            )
        )
    return facts


def entry_for_multi_asset(rec: MultiAssetRecord, as_of: date) -> DossierEntry:
    """Build a validated DossierEntry for a MultiAssetRecord."""
    return DossierEntry(
        instrument=Instrument(
            id=rec.code,
            name=rec.name,
            asset_class=rec.bucket,
            category=rec.category,
            plan_type=rec.plan,
        ),
        facts=facts_for_multi_asset(rec, as_of),
    )
