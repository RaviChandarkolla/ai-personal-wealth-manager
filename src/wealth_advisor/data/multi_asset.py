"""M13 multi-asset instrument catalog and deterministic Fact builders (13a-13d).

Covers:
- 13a Fixed Income (`fixed_income`): Public bank FD rate tables + debt metrics
  (FD rate, tenure, early-withdrawal penalty, DICGC ₹5L insurance limit, credit rating).
- 13b Commodity (`commodity`): Sovereign Gold Bonds (SGBs) + Gold ETFs
  (price trend, tracking error, expense ratio, 2.5% coupon, maturity).
- 13c Equity (`equity`): Nifty-50 large-cap universe
  (P/E vs sector P/E, earnings growth YoY, debt/equity, promoter pledging, insider activity).
- 13d Alternatives (`alt`): Listed REITs / InvITs only (skips PMS/AIF with ₹50L-₹1Cr minimums)
  (distribution yield, occupancy, NAV discount, leverage).
"""

